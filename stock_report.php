    $aWhere  = ["c.status = 'consignment'"];
    $aParams = [];
    if ($search !== '') {
        $aWhere[] = "(c.brand LIKE ? OR c.model LIKE ? OR c.trim_name LIKE ? OR c.car_year LIKE ? OR c.color LIKE ? OR c.chassis LIKE ? OR c.branch LIKE ? OR cn.dealer_name LIKE ?)";
        for ($i = 0; $i < 8; $i++) $aParams[] = "%$search%";
    }
    if ($selectedBranch !== '') { $aWhere[] = "c.branch = ?"; $aParams[] = $selectedBranch; }
    if ($selectedBrand  !== '') { $aWhere[] = "c.brand = ?";  $aParams[] = $selectedBrand; }
    if ($dateFrom       !== '') { $aWhere[] = "cn.started_at >= ?"; $aParams[] = $dateFrom . ' 00:00:00'; }
    if ($dateTo         !== '') { $aWhere[] = "cn.started_at <= ?"; $aParams[] = $dateTo   . ' 23:59:59'; }

    $aSql = "
        SELECT c.*, cn.dealer_name, cn.salesman, cn.started_at
        FROM cars c
        LEFT JOIN consignments cn ON cn.car_id = c.id AND cn.status = 'active'
        WHERE " . implode(' AND ', $aWhere) . "
        ORDER BY c.branch, c.brand, c.model, c.trim_name
    ";
    $aStmt = $pdo->prepare($aSql);
    $aStmt->execute($aParams);
    $amanaCars = $aStmt->fetchAll(PDO::FETCH_ASSOC);
